/**
 * Corpus CLI: writes the generated corpus and a measurement table.
 *
 *   node --import tsx synthetic-routes/report.ts [--write]
 *
 * --write refreshes corpus/corpus.json and corpus/measurements.md. Without it
 * the command only prints, so a check run never dirties the tree.
 */
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { FIXTURES } from "./fixtures";
import { evaluate, measure } from "./measure";
import { sample } from "./scenario";

async function main() {
  const write = process.argv.includes("--write");
  const rows: string[] = [];
  const corpus: unknown[] = [];
  let fails = 0;
  rows.push("| Fixture | Truth m | Client m | Accepted/delivered | Saveable | Moved | XP on Save | Server | Server m | Checks |");
  rows.push("|---|---:|---:|---:|---|---|---:|---|---:|---|");
  for (const f of FIXTURES) {
    const m = await measure(f);
    const checks = evaluate(f, m);
    const failed = checks.filter((c) => !c.pass);
    fails += failed.length;
    const srv = m.server.status;
    const srvM = "distanceMeters" in m.server && m.server.distanceMeters !== null ? String(m.server.distanceMeters) : "–";
    rows.push(`| ${f.id} | ${m.truthM.toFixed(0)} | ${m.client.distanceM.toFixed(0)} | ${m.client.accepted}/${m.client.fixesDelivered} | ${m.client.saveable} | ${m.client.movedOverGround} | ${m.client.xpBankedOnSave} | ${srv}${"reasons" in m.server && m.server.reasons.length ? ` (${m.server.reasons.join("; ")})` : ""} | ${srvM} | ${failed.length === 0 ? "PASS" : "FAIL: " + failed.map((c) => `${c.name} ${c.detail}`).join("; ")} |`);
    corpus.push({
      label: "SYNTHETIC / NOT LIVE", id: f.id, title: f.title, category: f.category, seed: f.scenario.seed,
      privacy: f.privacy, truth: f.truth, expect: f.expect, knownDefect: f.knownDefect ?? null,
      missingEvidence: f.missingEvidence ?? null,
      events: f.scenario.events, disturbances: f.scenario.disturbances ?? [],
      fixes: sample(f.scenario).filter((s) => s.reported).map((s) => ({
        t: s.second, lat: +s.reported!.latitude.toFixed(7), lng: +s.reported!.longitude.toFixed(7),
        acc: s.reported!.accuracy, spd: s.reported!.speed, sys: s.systemTime - s.gnssTime || undefined,
      })),
      measured: { truthM: Math.round(m.truthM), client: m.client, server: m.server, duplicate: m.duplicate, companion: m.companion },
      checks,
    });
  }
  const table = rows.join("\n");
  console.log(table);
  console.log(`\n${FIXTURES.length} fixtures, ${fails} failed checks`);
  if (write) {
    const dir = join(__dirname, "corpus");
    writeFileSync(join(dir, "corpus.json"), JSON.stringify({ label: "SYNTHETIC / NOT LIVE", generatedFrom: "synthetic-routes/fixtures.ts", fixtures: corpus }, null, 1) + "\n");
    writeFileSync(join(dir, "measurements.md"), `# Synthetic corpus measurements\n\nSYNTHETIC / NOT LIVE. Generated by \`synthetic-routes/report.ts --write\` against the code at this branch's base.\n\n${table}\n`);
  }
}
main().catch((e) => { console.error(e); process.exit(1); });
